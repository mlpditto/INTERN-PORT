const fs = require('node:fs');
const registry = require('../functions/ai-model-registry.json');
const target = 'public/ai-model-registry.js';
const content = '// Generated by scripts/build-ai-model-registry.cjs; edit functions/ai-model-registry.json.\nwindow.AI_MODEL_REGISTRY = ' + JSON.stringify(registry, null, 2) + ';\n';
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== content) throw new Error('Frontend model registry is stale');
} else fs.writeFileSync(target, content);
