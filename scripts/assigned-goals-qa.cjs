const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('public/quiz-merge.js','utf8');
const merge={};
vm.runInNewContext(source.slice(source.indexOf('    function canonical'),source.indexOf('    window.openQuizMerge'))+'globalThis.canonical=canonical;',merge);
const fingerprint=v=>JSON.stringify(merge.canonical(v));
assert.equal(fingerprint({title:'A',questions:[{text:'Q',choices:['a','b']}]}),fingerprint({questions:[{choices:['a','b'],text:'Q'}],title:'A'}));
assert.notEqual(fingerprint({questions:['a','b']}),fingerprint({questions:['b','a']}));
assert.notEqual(fingerprint({title:'A'}),fingerprint({title:'B'}));
const goal={window:{}};
vm.runInNewContext(fs.readFileSync('public/assigned-goals.js','utf8'),goal);
const row=(id,t,extra={})=>({id,quizId:id,status:'completed',timestamp:{toDate:()=>new Date(t)},...extra});
const range={start:'2026-09-01',end:'2026-09-30',targets:{quiz:2}};
const rows=[row('a','2026-09-01T00:00:00+07:00'),row('a','2026-09-02T12:00:00+07:00'),row('b','2026-09-30T23:59:59+07:00'),row('old','2026-08-31T23:59:59+07:00'),row('next','2026-10-01T00:00:00+07:00'),row('practice','2026-09-01T12:00:00+07:00',{isPractice:true}),row('draft','2026-09-01T12:00:00+07:00',{status:'draft'})];
assert.equal(goal.window.assignedGoals.count(rows,'quiz',range),2);
assert.equal(goal.window.assignedGoals.count(rows.filter(r=>r.id==='a'),'journal',range),1);
assert.equal(goal.window.assignedGoals.status(range,{quiz:2}),'Completed');
console.log('PASS assigned goal date boundaries, deduplication and merge map-order regression');
